/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{
  /* USER CODE BEGIN 1 */
	
  #ifdef W25Qxx
    SCB->VTOR = QSPI_BASE;
  #endif
  MPU_Config();
  CPU_CACHE_Enable();
	
  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_SPI4_Init();
  MX_TIM1_Init();
  /* USER CODE BEGIN 2 */
  DebugUart_Init();
  {
    char boot_line[80];
    (void)snprintf(boot_line, sizeof boot_line,
                   "[BOOT] reached UART initialization at %lu ms\r\n",
                   (unsigned long)HAL_GetTick());
    DebugUart_Print(boot_line);
  }
  DebugUart_Print("\r\n[H750] USART1 PB14(TX)/PB15(RX), 115200 8N1\r\n");
  {
    char clock_text[112];
    (void)snprintf(clock_text, sizeof(clock_text),
                   "[CLOCK] HSE=12000000 SYSCLK=%lu HCLK=%lu PCLK2=%lu Hz\r\n",
                   (unsigned long)HAL_RCC_GetSysClockFreq(),
                   (unsigned long)HAL_RCC_GetHCLKFreq(),
                   (unsigned long)HAL_RCC_GetPCLK2Freq());
    DebugUart_Print(clock_text);
  }
  DebugUart_Print("[BOOT] initializing ST7735...\r\n");
  const uint32_t lcd_start_tick = HAL_GetTick();
  LCD_InitSensors();
  {
    char lcd_line[90];
    (void)snprintf(lcd_line, sizeof lcd_line,
                   "[LCD] ready, init=%lu ms, uptime=%lu ms\r\n",
                   (unsigned long)(HAL_GetTick() - lcd_start_tick),
                   (unsigned long)HAL_GetTick());
    DebugUart_Print(lcd_line);
  }
  SensorTest_Init();
  uint32_t next_sensor_tick = HAL_GetTick();
  uint32_t last_heartbeat = HAL_GetTick();
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    uint32_t now = HAL_GetTick();
    if ((int32_t)(now - next_sensor_tick) >= 0)
    {
      SensorTest_Update();
      next_sensor_tick = HAL_GetTick() + 750U;
    }
    if ((uint32_t)(HAL_GetTick() - last_heartbeat) >= 1000U)
    {
      last_heartbeat = HAL_GetTick();
      char heartbeat[64];
      (void)snprintf(heartbeat, sizeof(heartbeat),
                     "[UART] alive uptime=%lu ms\r\n",
                     (unsigned long)last_heartbeat);
      DebugUart_Print(heartbeat);
    }
    DebugUart_PollEcho();
    HAL_Delay(2);
  }
  /* USER CODE END 3 */
}

